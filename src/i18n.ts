export type TranslationKey = keyof typeof messages.en;

function readLocale(): Locale {
  if (typeof window === 'undefined') return 'en';
  try {
    return window.localStorage.getItem(STORAGE_KEY) === 'zh' ? 'zh' : 'en';
  } catch {
    return 'en';
  }
}

const currentLocale = shallowRef<Locale>(readLocale());

export function setLocale(next: Locale): void {
  currentLocale.value = next;
  if (typeof window !== 'undefined') {
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      // Local persistence is best effort; the in-memory switch still applies.
    }
  }
}

export function translate(key: TranslationKey, params: MessageParams = {}): string {
  const selected = (messages[currentLocale.value] as Partial<Record<TranslationKey, string>>)[key]
    ?? messages.en[key]
    ?? key;
  return selected.replace(/\{(\w+)\}/g, (match, name: string) => String(params[name] ?? match));
}

export function formatDateTime(value: number | null | undefined, options?: Intl.DateTimeFormatOptions): string {
  if (!value) return '';
  return new Intl.DateTimeFormat(currentLocale.value === 'zh' ? 'zh-CN' : 'en-US', options).format(new Date(value));
}

export function formatTime(value: number | null | undefined): string {
  return formatDateTime(value, { hour: '2-digit', minute: '2-digit' });
}

export function useI18n() {
  return {
    locale: readonly(currentLocale),
    t: translate,
    setLocale,
  };
}
